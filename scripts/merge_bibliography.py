"""Merge related works by DOI or normalized title, retaining citation keys as BibLaTeX ids."""
from pathlib import Path
import re,json,hashlib
from bib_utils import parse,dump,norm
all_entries=[];seen={};manifest=[]
for p in sorted(Path('bibliography').glob('*.bib')):
 for e in parse(p.read_text()):
  if e['key'] in seen:raise SystemExit('Duplicate key '+e['key'])
  e['source']=str(p);all_entries.append(e);seen[e['key']]=e
 manifest.append({'path':str(p),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()})
parent=list(range(len(all_entries)))
def root(i):
 while parent[i]!=i:i=parent[i]
 return i
idx={}
for i,e in enumerate(all_entries):
 f=e['fields'];ids=[('title',norm(f.get('title','')))]
 if f.get('doi'):ids.append(('doi',f['doi'].lower().replace('https://doi.org/','')))
 for tag in ids:
  if not tag[1]:continue
  if tag in idx:parent[root(i)]=root(idx[tag])
  idx[tag]=i
groups={}
for i,e in enumerate(all_entries):groups.setdefault(root(i),[]).append(e)
def score(e):
 f=e['fields'];return (10*e['key'].startswith('bg-')+8*bool(f.get('doi'))+4*bool(f.get('year'))+2*bool(f.get('pages'))-5*('arxiv' in f.get('journal','').lower())-2*(' and others' in f.get('author','')))
out=[];audit=[];aliases={}
for es in groups.values():
 es.sort(key=score,reverse=True);best=es[0];f=dict(best['fields'])
 # Fill absent non-container fields; no automatic mixing of journal and conference versions.
 for e in es[1:]:
  for k,v in e['fields'].items():
   if k not in f and k not in ['journal','booktitle','publisher','year','date','volume','number','pages','editor']:f[k]=v
 ids=[e['key'] for e in es if e!=best]
 if ids:f['ids']=','.join(ids)
 for e in es:aliases[e['key']]=best['key']
 out.append({'type':best['type'],'key':best['key'],'fields':f})
 if len(es)>1:audit.append({'canonical':best['key'],'aliases':ids,'source_entries':es})
Path('thesis-references.bib').write_text('% Generated by scripts/merge_bibliography.py; edit bibliography/ fragments.\n\n'+'\n'.join(dump(e) for e in out))
Path('planning/bibliography-fragments.json').write_text(json.dumps(manifest,indent=2))
Path('planning/bibliography-deduplication.json').write_text(json.dumps(audit,indent=2,ensure_ascii=False))
Path('planning/bibliography-key-aliases.json').write_text(json.dumps(aliases,indent=2))
print(len(all_entries),'source entries ->',len(out),'unique works;',sum(len(g['aliases']) for g in audit),'aliases retained')
